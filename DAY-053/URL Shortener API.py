# The SQLAlchemy model represents the database structure, while the client should only provide the data they're allowed to control. Fields like id, clicks, created_at, and short_code are server-managed. Allowing clients to send them could lead to data manipulation and security issues. Therefore, we use Pydantic schemas to expose only the fields the client is permitted to send or receive.







