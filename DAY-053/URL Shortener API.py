# Let's Understand It

# Why BaseModel?
# Every Pydantic schema inherits from: BaseModel
# Just like every SQLAlchemy model inherits from: Base

# Think of it like this: 
# SQLAlchemy Model → Base
# Pydantic Schema → BaseModel

# Why HttpUrl instead of str?
# This is one of the coolest FastAPI features.

# Imagine someone sends:
{
    "original_url": "hello"
}
# If we use: str It accepts it. But... Is "hello" a valid URL? No.
# If we use: HttpUrl Pydantic automatically validates it.

# Example:
# https://google.com --> Accepted
# https://github.com/Adyaprana --> Accepted
# google --> Rejected
# abc123 --> Rejected
# hello --> Rejected

# FastAPI automatically returns: 422 Unprocessable Entity without us writing any validation code.


# This is why FastAPI is loved
# With Flask, we'd have to write validation ourselves.
# With FastAPI: Client → Pydantic → Validation → FastAPI → Our Code
# Our endpoint only receives valid data.


