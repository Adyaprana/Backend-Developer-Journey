# Two new things today

# 1. ConfigDict(from_attributes=True)
# This is another SQLAlchemy 2.x improvement.
# Old tutorials use:
# class Config:
    # orm_mode = True

# That's Pydantic v1.
# We're using: Pydantic v2, SQLAlchemy 2.x
# So the modern equivalent is: model_config = ConfigDict(from_attributes=True)

# What does it do -> Imagine later we return a SQLAlchemy object.
# Example: url = ShortenedURL(...)
# Instead of manually writing:
# {
#     "id": url.id,
#     "original_url": url.original_url,
#     ...
# }
# Pydantic can automatically read attributes from the SQLAlchemy model and convert them into the API response.
# Think of it like: SQLAlchemy Model → Pydantic Schema → JSON Response


# 2. Why no id in URLCreate?

# Because: The client doesn't create IDs. The database creates them.
# This is one of the biggest lessons today. Request schemas contain only what the client is allowed to send.



# 🎤 Interview Questions (Day 53)

# Q1. What is the difference between a SQLAlchemy Model and a Pydantic Schema?
# Answer: SQLAlchemy Model → Defines how data is stored in the database.
#         Pydantic Schema → Defines what data the API accepts and returns.

# Q2. Why don't we use SQLAlchemy models directly as request bodies?
# Answer: Because the client should not control database-managed fields like id, clicks, created_at, or short_code. Schemas expose only the fields the client is allowed to send.

# Q3. Why use HttpUrl instead of str?
# Answer: HttpUrl automatically validates that the input is a valid HTTP or HTTPS URL. Invalid URLs are rejected before our endpoint logic runs.

# Q4. What does from_attributes=True do?
# Answer: It allows Pydantic to create response objects directly from SQLAlchemy model instances by reading their attributes.

# Q5. Why have separate request and response schemas?
# Answer: The data the client sends is often different from the data the server returns. Separate schemas make the API safer, clearer, and easier to maintain.