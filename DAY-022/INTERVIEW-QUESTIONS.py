# INTERVIEW QUESTIONS: 

# Q1. What is HTTP?
# Answer: HTTP (HyperText Transfer Protocol) is the communication protocol used between clients and servers.

# Q2. What is Client?
# Answer: Application requesting data.
# Examples:
# Browser
# Mobile App

# Q3. What is Server?
# Answer: Application that processes requests and sends responses.

# Q4. What is GET?
# Answer: Used to retrieve data.

# Q5. What is POST?
# Answer: Used to create data.

# Q6. Difference between PUT and PATCH?
# Answer:   PUT: Replace entire resource.
#           PATCH: Update only specific fields.

# Q7. What is DELETE?
# Answer: Used to remove data.

# Q8. What is Status Code 200?
# Answer: Request successful.

# Q9. What is Status Code 201?
# Answer: Resource created successfully.

# Q10. What is Status Code 401?
# Answer: Authentication required.

# Q11. What is Status Code 403?
# Answer: Access denied.

# Q12. What is Status Code 404?
# Answer: Resource not found.

# Q13. What is Status Code 422?
# Answer: Validation error --> Very common in FastAPI.

# Q14. What is Status Code 500?
# Answer: Internal server error.

# Q15. What is Request Body?
# Answer: Data sent from client to server.

# Q16. What is Header?
# Answer: Metadata about request or response.

# Q17. What is Query Parameter?
# Answer: Used for filtering/searching.
# Example: /products?page=1

# Q18. What is Path Parameter?
# Answer: Part of URL path.
# Example: /users/10

# Q19. Why should backend developers learn HTTP?
# Answer: Because every API is built on HTTP.

# Q20. What is REST API?
# Answer: An API that uses HTTP methods and resources following REST principles.