# Arithmetic operators (+, -, *, /, //, %, **)

num1 = 5
num2 = 4

print("1st number is: ",num1)
print("2nd number is: ",num2)

print("Addition of these two number is: ",num1+num2)
print("Subtraction of these two number is: ",num1-num2)

mul = num1*num2
print("Multiplication of these two number is: ",mul)

div = num1/num2
print("Division of these two number is: ",div)

print("Floor Division of these two number is: ",num1//num2)
print("Modulus of these two number is: ",num1%num2)
print("Power of these two number is: ",num1**num2)
