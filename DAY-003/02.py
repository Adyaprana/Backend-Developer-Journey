# Comparison Operators
# its used to compare two values and return a boolean value (True or False)
# ==, !=, >, <, >=, <=
# Operator                                    Description
# == (Equal to)                               Returns True if both operands are equal
# != (Not equal to)                           Returns True if both operands are not equal
# > (Greater than)                            Returns True if left operand is greater than right operand    
# < (Less than)                               Returns True if left operand is less than right operand
# >= (Greater than or equal to)               Returns True if left operand is greater than or
# <= (Less than or equal to)                  Returns True if left operand is less than or equal to right operand
# Example:

num1 = 5
num2 = 3
print("num1 is: ", num1)
print("num2 is: ", num2)
print("is num1 equal to num2?", num1 == num2)
print("is num1 not equal to num2?", num1 != num2)
print("is num1 greater than num2?", num1 > num2)
print("is num1 less than num2?", num1 < num2)
print("is num1 greater than or equal to num2?", num1 >= num2)
print("is num1 less than or equal to num2?", num1 <= num2)


print (5 == 5) # True
print (5 != 5) # False
print (5 > 3) # True
print (5 < 3) # False
print (5 >= 5) # True
print (5 <= 5) # True

