# INTERVIEW QUESTIONS:

# Q1. What is Requests Library?
# Answer: A Python library used to send HTTP requests.

# Q2. How do you install requests?
# Answer: pip install requests

# Q3. What is an API?
# Answer: A mechanism that allows software applications to communicate.

# Q4. What is GET request?
# Answer: Used to retrieve data from a server.

# Q5. What is POST request?
# Answer: Used to send data to a server.

# Q6. What does response.json() do?
# Answer: Converts JSON response into Python dictionary.

# Q7. What does response.status_code return?
# Answer: HTTP response status code.

# Q8. What does response.headers return?
# Answer: Response metadata.

# Q9. What does status code 200 mean?
# Answer: Success.

# Q10. What does status code 404 mean?
# Answer: Resource not found.

# Q11. What does status code 500 mean?
# Answer: Server-side error.

# Q12. Why is timeout important?
# Answer: Prevents application from waiting forever.

# Q13. Why are APIs important in backend development?
# Answer: Modern applications communicate through APIs.

# Q14. What datatype does response.json() usually return?
# Answer: Dictionary (dict) or List (list).

# Q15. Why should backend developers learn requests?
# Answer: Because backend services frequently communicate with external APIs such as GitHub, Weather, Payment, Maps, AI, and Authentication services.