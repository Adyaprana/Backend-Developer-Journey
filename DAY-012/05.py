# WHAT IS PIP?
# PIP = Python Package Installer

# Think:
# Play Store for Python
# Without pip:
# No FastAPI.
# No Flask.
# No Django.
# No Requests.
# No Pandas.

# INSTALL PACKAGE
# pip install requests

# Install Flask
# pip install flask

# Install FastAPI
# pip install fastapi

# See Installed Packages
# pip list

# Package Information
# pip show flask

# Update Package
# pip install --upgrade flask

# Remove Package
# pip uninstall flask