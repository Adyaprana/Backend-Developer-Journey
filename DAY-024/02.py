# INTERVIEW QUESTIONS: 

# Q1. What is Git?
# Answer: Distributed version control system used to track code changes.

# Q2. What is GitHub?
# Answer: Cloud platform for hosting Git repositories.

# Q3. Difference between Git and GitHub?
# Answer: Git = Tool \\ GitHub = Hosting platform

# Q4. What does git init do?
# Answer: Creates a new Git repository.

# Q5. What does git status show?
# Answer: Current repository state.

# Q6. What does git add do?
# Answer: Moves changes to staging area.

# Q7. What does git commit do?
# Answer: Creates snapshot of staged changes.

# Q8. What is a branch?
# Answer: Independent line of development.

# Q9. Why use branches?
# Answer: Develop features safely without affecting main code.

# Q10. What does git merge do?
# Answer: Combines branches.

# Q11. What does git pull do?
# Answer: Downloads latest remote changes.

# Q12. What does git push do?
# Answer: Uploads commits to GitHub.

# Q13. What is git clone?
# Answer: Copies repository to local machine.

# Q14. What is .gitignore?
# Answer: File specifying what Git should ignore.

# Q15. What is git stash?
# Answer: Temporarily saves uncommitted work.