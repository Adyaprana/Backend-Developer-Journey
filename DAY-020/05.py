# TOP INTERVIEW QUESTIONS:


# Q1. What is OOP?
# Answer: Object-Oriented Programming is a programming paradigm that organizes code using classes and objects.

# Q2. What is a Class?
# Answer: A blueprint used to create objects.

# Q3. What is an Object?
# Answer: An instance of a class.

# Q4. What is init()?
# Answer: Constructor method automatically called during object creation.

# Q5. What is self?
# Answer: Reference to the current object.

# Q6. What is Encapsulation?
# Answer: Protecting data by restricting direct access.

# Q7. What is Inheritance?
# Answer: Creating a new class from an existing class.

# Q8. What is Polymorphism?
# Answer: Same method name with different behavior.

# Q9. What is Abstraction?
# Answer: Hiding implementation details.

# Q10. Difference between Class and Object?
# Answer: Class: Blueprint.
#         Object: Actual instance.

# Q11. Can Python support multiple inheritance?
# Answer: Yes.
# class A:
#     pass
# class B:
#     pass
# class C(A, B):
#     pass

# Q12. What is Method Overriding?
# Answer: Child class replaces parent method.

# Q13. What is Method Resolution Order (MRO)?
# Answer: Order Python follows to find methods.

# Q14. Why is OOP useful?
# Answer: Makes code: Reusable, Organized, Maintainable, Scalable.

# Q15. How is OOP used in backend development?
# Answer: Everything in modern backend development is modeled using objects:
#         Users, Orders, Products, Payments, API Services, Database Models.