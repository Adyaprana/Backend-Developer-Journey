# INTERVIEW QUESTIONS:

# Q1. What is an API?
# Answer: A mechanism allowing software applications to communicate.

# Q2. What does REST stand for?
# Answer: Representational State Transfer.

# Q3. Who created REST?
# Answer: Roy Fielding.

# Q4. What is Statelessness?
# Answer: Each request contains all required information, Server does not remember previous requests.

# Q5. Most important REST constraint?
# Answer: Statelessness.

# Q6. Difference between GET and POST?
# Answer: GET fetches data \\ POST creates data.

# Q7. Difference between PUT and PATCH?
# Answer: PUT replaces entire resource \\\ PATCH updates only specific fields.

# Q8. What does HTTP 200 mean?
# Answer: Request successful.

# Q9. What does HTTP 201 mean?
# Answer: Resource created successfully.

# Q10. What does HTTP 404 mean?
# Answer: Resource not found.

# Q11. What does HTTP 500 mean?
# Answer: Internal server error.

# Q12. What is JSON?
# Answer: Lightweight data exchange format.

# Q13. Difference between JSON Object and Array?
# Answer: Object: {} \\ Array: []

# Q14. Why is JSON popular?
# Answer: Easy to read, lightweight, language-independent.

# Q15. Why are APIs important for backend developers?
# Answer: Because backend systems communicate primarily through APIs.
