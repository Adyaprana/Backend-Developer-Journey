# THEORY 1 — WHAT IS AN API?

# API = Application Programming Interface
# An API is a set of rules that allows two software systems to communicate.

# Real meaning:
# API = Messenger between two software systems

# Real Life Example
# Restaurant:
# Customer
#   ↓
# Waiter
#   ↓
# Kitchen

# Customer: Frontend
# Waiter: API
# Kitchen: Backend

# Customer asks: Give me pizza
# API carries request.
# Kitchen makes pizza.
# API returns response.

# Same in software.

# Example:
# Instagram App
# You open app.
# App says: Give me my profile
# API: GET /profile
# Server returns:
{
  "name": "Adyaprana",
  "followers": 1200
}