# Uses HTTP.
# Request: Client → Server
# Response: Server → Client


# THEORY 5 — HTTP METHODS

# GET --> Fetch data.
# Example: GET /users
# Meaning: Give me users

# POST --> Create data.
# Example: POST /users
# Meaning: Create new user

# PUT --> Replace existing data.
# Example: PUT /users/1
# Meaning: Replace existing data.

# PATCH --> Update part of data.
# Example: PATCH /users/1
# Meaning: Update part of data.

# DELETE --> Delete resource.
# Example: DELETE /users/1
# Meaning: Delete resource.


# MEMORY TRICK
# GET     → Read
# POST    → Create
# PUT     → Replace
# PATCH   → Update
# DELETE  → Remove


# THEORY 5 — HTTP STATUS CODES

# 200 OK --> Success.
# 201 Created --> New resource created.
# 400 Bad Request --> Client sent invalid data.
# 401 Unauthorized --> Not logged in.
# 403 Forbidden --> Logged in but no permission.
# 404 Not Found --> Resource doesn't exist.
# 500 Internal Server Error --> Backend crashed.

# Memory Trick:
# 2xx Success
# 4xx Client Error
# 5xx Server Error
