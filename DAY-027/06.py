# THEORY 7 — is vs ==

a = [1,2]
b = [1,2]
print(a == b)
# Output: True -> Same values.
print(a is b)
# Output: False -> Different objects.
# Rule: 
# == --> Compare values.
# is --> Compare memory identity.



